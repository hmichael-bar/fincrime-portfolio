"""Pull the supporting transaction data for SAR 1 and SAR 2 out of project 03's synthetic dataset.

SYNTHETIC DATA ONLY. Writes CSVs and markdown tables to ../supporting_data/ so every
number quoted in the SAR narratives can be traced back to a transaction ID.

Run from the 04-sar-narratives folder (uses project 03's virtualenv):
    ../03-transaction-monitoring/.venv/bin/python tools/extract_case_data.py
"""
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parents[1]
TM = HERE.parent / "03-transaction-monitoring"
OUT = HERE / "supporting_data"
OUT.mkdir(exist_ok=True)

tx = pd.read_csv(TM / "data" / "transactions.csv", parse_dates=["timestamp"], keep_default_na=False)
cust = pd.read_csv(TM / "data" / "customers.csv").set_index("customer_id")
branches = pd.read_csv(TM / "data" / "branches.csv").set_index("branch_id")
COLS = ["txn_id", "timestamp", "txn_type", "amount", "branch_id", "branch_state", "counterparty_name",
        "counterparty_country", "memo", "device_id"]


def md(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |\n|" + "|".join("---" for _ in df.columns) + "|\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False))


def money(x):
    return f"${x:,.2f}"


sections = ["# Supporting data extracted from project 03 (synthetic)\n",
            "Generated by `tools/extract_case_data.py`. Do not edit by hand.\n"]

# ---------------------------------------------------------------- SAR 1: structuring (C0298)
s1 = tx[tx.customer_id == "C0298"].copy()
cash = s1[(s1.txn_type == "CASH_DEPOSIT") & (s1.amount >= 8000)]
outs = s1[(s1.txn_type == "ACH_OUT") & (s1.memo == "TRANSFER TO OWN ACCOUNT")]
sar1 = pd.concat([cash, outs]).sort_values("timestamp")
sar1[COLS].to_csv(OUT / "SAR-01_structuring_transactions.csv", index=False)
t = sar1.assign(date=sar1.timestamp.dt.strftime("%m/%d/%Y"), time=sar1.timestamp.dt.strftime("%H:%M"),
                location=sar1.branch_id.map(lambda b: f"{b} {branches.city[b]}, {branches.state[b]}" if b else "Online/ACH"),
                amt=sar1.amount.map(money),
                desc=sar1.apply(lambda r: "Cash deposit" if r.txn_type == "CASH_DEPOSIT" else f"ACH debit to {r.counterparty_name}", axis=1))
sections += ["## SAR 1: C0298 cash deposits ≥ $8,000 and outbound transfers\n",
             md(t[["txn_id", "date", "time", "desc", "amt", "location"]].rename(columns={"amt": "amount"})),
             f"\n**Cash deposits:** {len(cash)} totalling {money(cash.amount.sum())}; **outbound ACH:** {len(outs)} totalling {money(outs.amount.sum())}\n"]
pay = s1[s1.txn_type == "ACH_IN"]
sections.append(f"Payroll credits (context): {len(pay)} from {pay.counterparty_name.iloc[0]}, total {money(pay.amount.sum())}, average {money(pay.amount.mean())}\n")

# ---------------------------------------------------------------- SAR 2: mule network
MULE = "C0221"
COLLECTORS = ["C0057", "C0106"]
m = tx[tx.customer_id == MULE].copy()
start = pd.Timestamp("2026-02-22")
victims = m[(m.txn_type.isin(["P2P_IN", "ACH_IN"])) & (m.timestamp >= start) & (m.amount >= 250)
            & (m.counterparty_name != "TaskHub Inc")]
m_out = m[(m.timestamp >= start) & (m.txn_type.isin(["P2P_OUT", "CRYPTO_BUY", "CASH_WITHDRAWAL"])) & (m.amount >= 1000)]
victims[COLS].to_csv(OUT / "SAR-02_mule_inbound_victim_payments.csv", index=False)
m_out[COLS].to_csv(OUT / "SAR-02_mule_outbound.csv", index=False)

monthly = pd.DataFrame({
    "inbound_from_individuals": victims.groupby(victims.timestamp.dt.strftime("%Y-%m")).amount.sum(),
    "senders": victims.groupby(victims.timestamp.dt.strftime("%Y-%m")).counterparty_account.nunique(),
    "to_collectors": m_out[m_out.txn_type == "P2P_OUT"].groupby(m_out.timestamp.dt.strftime("%Y-%m")).amount.sum(),
    "crypto": m_out[m_out.txn_type == "CRYPTO_BUY"].groupby(m_out.timestamp.dt.strftime("%Y-%m")).amount.sum(),
    "cash": m_out[m_out.txn_type == "CASH_WITHDRAWAL"].groupby(m_out.timestamp.dt.strftime("%Y-%m")).amount.sum(),
}).fillna(0)
monthly.loc["Total"] = monthly.sum()
mt = monthly.reset_index().rename(columns={"index": "month"})
for col in ["inbound_from_individuals", "to_collectors", "crypto", "cash"]:
    mt[col] = mt[col].map(money)
mt["senders"] = mt["senders"].astype(int)
sections += [f"## SAR 2: {MULE} ({cust.name[MULE]}) monthly flow since {start.date()}\n", md(mt), ""]

dest = m_out.groupby(["txn_type", "counterparty_name"]).amount.agg(["count", "sum"]).reset_index()
dest["sum"] = dest["sum"].map(money)
sections += ["### Where the mule's money went (≥ $1,000)\n", md(dest), ""]
memo = victims.memo.replace("", "(blank)").value_counts().reset_index()
sections += ["### Memos on inbound payments\n", md(memo), ""]
first = victims.sort_values("timestamp").head(12)
first_t = first.assign(date=first.timestamp.dt.strftime("%m/%d/%Y"), amt=first.amount.map(money))[["txn_id", "date", "txn_type", "amt", "counterparty_name", "memo"]]
sections += ["### First 12 inbound payments after 02/22/2026\n", md(first_t), ""]

mule_ids = ["C0057", "C0106", "C0197", "C0221", "C0255", "C0316", "C0317", "C0416", "C0454", "C0484"]
acct = cust.account_no.to_dict()
rows = []
for cid in mule_ids:
    x = tx[tx.customer_id == cid]
    reg_dev = cust.device_id[cid]
    rows.append(dict(customer=cid, name=cust.name[cid], age=cust.age[cid], occupation=cust.occupation[cid],
                     state=cust.home_state[cid], opened=cust.account_open_date[cid], device=reg_dev,
                     total_in=money(x[x.direction == "IN"].amount.sum()), total_out=money(x[x.direction == "OUT"].amount.sum())))
net = pd.DataFrame(rows)
net.to_csv(OUT / "SAR-02_network_accounts.csv", index=False)
sections += ["### Linked accounts (shared devices / P2P flows)\n", md(net), ""]

for col in COLLECTORS:
    x = tx[tx.customer_id == col]
    pin = x[(x.txn_type == "P2P_IN") & x.counterparty_account.isin([acct[c] for c in mule_ids])]
    w = x[x.txn_type == "WIRE_OUT"]
    cb = x[x.txn_type == "CRYPTO_BUY"]
    w.groupby(["counterparty_name", "counterparty_country"]).amount.agg(["count", "sum"])
    by_mule = pin.groupby("counterparty_name").amount.agg(["count", "sum"]).sort_values("sum", ascending=False).reset_index()
    by_mule["sum"] = by_mule["sum"].map(money)
    wires = w.groupby(["counterparty_name", "counterparty_country"]).amount.agg(["count", "sum"]).reset_index()
    wires["sum"] = wires["sum"].map(money)
    pd.concat([pin, w, cb])[COLS].sort_values("timestamp").to_csv(OUT / f"SAR-02_collector_{col}.csv", index=False)
    sections += [f"### Collector {col} ({cust.name[col]}, {cust.occupation[col]}, {cust.home_state[col]}, opened {cust.account_open_date[col]})\n",
                 f"P2P received from linked accounts: {len(pin)} totalling {money(pin.amount.sum())} "
                 f"({pin.timestamp.min():%m/%d/%Y} to {pin.timestamp.max():%m/%d/%Y})\n", md(by_mule), "",
                 f"International wires out: {len(w)} totalling {money(w.amount.sum())}; crypto purchases: {len(cb)} totalling {money(cb.amount.sum())}\n",
                 md(wires), ""]

(OUT / "SUPPORTING_TABLES.md").write_text("\n".join(sections))
print("wrote", OUT)
