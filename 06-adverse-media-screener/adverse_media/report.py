"""Markdown, HTML and JSON adverse-media reports."""
from __future__ import annotations

import html
import json
from collections import defaultdict
from pathlib import Path

from .analyze import RELEVANCE_MULT
from .keywords import CATEGORIES, STAGES
from .screener import ScreeningRun

STAGE_LABEL = {k: v["label"] for k, v in STAGES.items()} | {"none": "Not stated"}
MAX_ROWS = 25


def _category_summary(run: ScreeningRun):
    agg = defaultdict(lambda: {"n": 0, "max": 0, "latest": None})
    for f in run.adverse:
        for c in f.categories:
            a = agg[c]
            a["n"] += 1
            a["max"] = max(a["max"], f.severity)
            d = f.article.published
            if d and (a["latest"] is None or d > a["latest"]):
                a["latest"] = d
    return sorted(agg.items(), key=lambda kv: (-kv[1]["max"], -kv[1]["n"]))


def _date(d) -> str:
    return d.strftime("%Y-%m-%d") if d else "n/a"


def _cats(f) -> str:
    return ", ".join(CATEGORIES[c]["label"] for c in f.categories)


def _top_findings_text(run: ScreeningRun, n: int = 5) -> list[str]:
    return [f"{_date(f.article.published)} {f.article.source}: \"{f.article.title}\" "
            f"({_cats(f)}; {STAGE_LABEL[f.stage].lower()})" for f in run.adverse[:n]]


def to_markdown(run: ScreeningRun) -> str:
    s = run.subject
    L = [f"# Adverse Media Report: {s.name}", ""]
    L.append(f"*Run {run.run_at:%Y-%m-%d %H:%M} UTC · look-back {run.days} days · subject type: {s.kind}*  ")
    if s.aliases or s.arabic_names:
        L.append(f"*Also searched as: {', '.join(s.aliases + s.arabic_names)}*")
    L += ["", f"## Overall risk: **{run.rating}**", "", run.rating_reason, ""]
    L.append(f"- Articles retrieved: **{run.raw_count}** → unique stories after de-duplication: "
             f"**{len(run.findings)}**")
    L.append(f"- Adverse stories (risk keywords + subject named + severity ≥ 40): **{len(run.adverse)}**")
    by_lang = defaultdict(int)
    for f in run.adverse:
        by_lang[f.article.language] += 1
    if by_lang:
        L.append("- Adverse stories by language: " + ", ".join(f"{k}: {v}" for k, v in sorted(by_lang.items())))
    L += ["", "## Risk categories", "", "| Category | Stories | Max severity | Most recent |", "|---|---|---|---|"]
    for c, a in _category_summary(run):
        L.append(f"| {CATEGORIES[c]['label']} | {a['n']} | {a['max']:.0f} | {_date(a['latest'])} |")
    if not run.adverse:
        L.append("| – | 0 | – | – |")
    L += ["", f"## Adverse findings (top {min(MAX_ROWS, len(run.adverse))} of {len(run.adverse)}, most severe first)", "",
          "| Sev. | Date | Source | Headline | Categories | Stage | Subject named in |", "|---|---|---|---|---|---|---|"]
    for f in run.adverse[:MAX_ROWS]:
        a = f.article
        title = a.title.replace("|", "/")
        extra = f" (+{len(f.also_reported_by)} outlets)" if f.also_reported_by else ""
        mit = " ⚠️ mitigating: " + ", ".join(f.mitigating) if f.mitigating else ""
        L.append(f"| {f.severity:.0f} | {_date(a.published)} | {a.source}{extra} | [{title}]({a.url}){mit} | "
                 f"{_cats(f)} | {STAGE_LABEL[f.stage]} | {f.relevance} |")
    L += ["", "## Searches performed", "", "| Source | Status | Results | Query |", "|---|---|---|---|"]
    for lg in run.logs:
        L.append(f"| {lg.source} | {lg.status} | {lg.n_results} | `{lg.query}` |")
    L += ["", "## How to read this report", "",
          "- **Severity (0–100)** = category weight × legal-stage multiplier × relevance multiplier. "
          "Weights: " + ", ".join(f"{v['label']} {v['weight']}" for v in CATEGORIES.values()) + ". "
          "Stage: " + ", ".join(f"{v['label']} ×{v['multiplier']}" for v in STAGES.values()) + ", not stated ×0.75. "
          "Relevance: " + ", ".join(f"{k} ×{v}" for k, v in RELEVANCE_MULT.items()) + ". "
          "Exculpatory wording (acquitted, delisted, sanctions lifted) ×0.7.",
          "- Matching is on headlines and feed snippets only. **Every finding must be opened and read** "
          "before it is relied on: confirm the article is about this subject (not a namesake), "
          "check the outlet's credibility, and record the conclusion in the customer file.",
          "- Media reports are not proof. Allegations should be weighed by source quality and corroboration.",
          "", "*Generated by adverse-media-screener (portfolio project). Public news sources only.*"]
    return "\n".join(L)


