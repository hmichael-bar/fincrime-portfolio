def to_html(run: ScreeningRun) -> str:
    e = html.escape
    s = run.subject
    rows = []
    for f in run.adverse[:MAX_ROWS]:
        a = f.article
        extra = f"<br><span class=meta>+ {e(', '.join(f.also_reported_by[:4]))}</span>" if f.also_reported_by else ""
        mit = f"<br><span class=mit>mitigating: {e(', '.join(f.mitigating))}</span>" if f.mitigating else ""
        rows.append(f"<tr><td class=sev>{f.severity:.0f}</td><td>{_date(a.published)}</td><td>{e(a.source)}{extra}</td>"
                    f"<td dir=auto><a href=\"{e(a.url)}\" target=_blank rel=noopener>{e(a.title)}</a>{mit}</td>"
                    f"<td>{e(_cats(f))}</td><td>{e(STAGE_LABEL[f.stage])}</td><td>{e(f.relevance)}</td></tr>")
    cats = "".join(f"<tr><td>{e(CATEGORIES[c]['label'])}</td><td>{a['n']}</td><td>{a['max']:.0f}</td>"
                   f"<td>{_date(a['latest'])}</td></tr>" for c, a in _category_summary(run)) or \
        "<tr><td colspan=4>No adverse categories</td></tr>"
    logs = "".join(f"<tr><td>{e(l.source)}</td><td>{e(l.status)}</td><td>{l.n_results}</td>"
                   f"<td dir=auto><code>{e(l.query)}</code></td></tr>" for l in run.logs)
    langs = defaultdict(int)
    for f in run.adverse:
        langs[f.article.language] += 1
    also = e(", ".join(s.aliases + s.arabic_names))
    return f"""<!doctype html><html lang=en><head><meta charset=utf-8>
<meta name=viewport content="width=device-width,initial-scale=1"><title>Adverse Media – {e(s.name)}</title>
<style>{CSS}</style></head><body><main>
<h1>Adverse Media Report: {e(s.name)}</h1>
<div class=meta>Run {run.run_at:%Y-%m-%d %H:%M} UTC · look-back {run.days} days · {e(s.kind)}{(' · also searched as: ' + also) if also else ''}</div>
<h2>Overall risk <span class="badge {run.rating}">{run.rating}</span></h2><p>{e(run.rating_reason)}</p>
<div class=cards><div class=card><b>{run.raw_count}</b>articles retrieved</div>
<div class=card><b>{len(run.findings)}</b>unique stories</div><div class=card><b>{len(run.adverse)}</b>adverse stories</div>
<div class=card><b>{langs.get('en', 0)} / {langs.get('ar', 0)}</b>adverse EN / AR</div></div>
<h2>Risk categories</h2><div class=wrap><table><tr><th>Category</th><th>Stories</th><th>Max severity</th><th>Most recent</th></tr>{cats}</table></div>
<h2>Adverse findings (top {min(MAX_ROWS, len(run.adverse))} of {len(run.adverse)})</h2>
<div class=wrap><table><tr><th>Sev.</th><th>Date</th><th>Source</th><th>Headline</th><th>Categories</th><th>Stage</th><th>Named in</th></tr>{''.join(rows)}</table></div>
<h2>Searches performed</h2><div class=wrap><table><tr><th>Source</th><th>Status</th><th>Results</th><th>Query</th></tr>{logs}</table></div>
<h2>How to read this report</h2><p class=meta>Severity = category weight × legal-stage multiplier × relevance multiplier (see HOW_IT_WORKS.md).
Matching uses headlines and feed snippets only: every finding must be opened, confirmed to concern this subject (not a namesake),
weighed by source credibility and documented before it is relied on. Media reports are not proof.</p>
<p class=meta>Generated by adverse-media-screener (portfolio project). Public news sources only.</p>
</main></body></html>"""


def to_json(run: ScreeningRun) -> str:
    return json.dumps({
        "subject": {"name": run.subject.name, "aliases": run.subject.aliases,
                    "arabic_names": run.subject.arabic_names, "kind": run.subject.kind},
        "run_at": run.run_at.isoformat(), "days": run.days, "rating": run.rating,
        "rating_reason": run.rating_reason, "raw_articles": run.raw_count,
        "unique_stories": len(run.findings), "adverse_stories": len(run.adverse),
        "searches": [vars(l) for l in run.logs],
        "findings": [f.to_dict() for f in run.findings],
    }, indent=2, ensure_ascii=False)


def write_all(run: ScreeningRun, out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    slug = "".join(ch if ch.isalnum() else "_" for ch in run.subject.name.lower()).strip("_")
    paths = {"md": out_dir / f"{slug}.md", "html": out_dir / f"{slug}.html", "json": out_dir / f"{slug}.json"}
    paths["md"].write_text(to_markdown(run), encoding="utf-8")
    paths["html"].write_text(to_html(run), encoding="utf-8")
    paths["json"].write_text(to_json(run), encoding="utf-8")
    return paths
